//! 多语言文案目录：繁体中文 / 日语 / 俄语。
//!
//! # 为什么用覆盖表而不是把三元组写进调用点
//!
//! [`super::Bi`] 是 `(中文, English)` 二元组，**写在调用点上**——这是本项目
//! i18n 的设计根基（见 `i18n.rs` 模块文档：缺英文、语义漂移在评审里一眼
//! 可见）。三种新增语言若也内联，调用点要写成五元组：
//!
//! ```ignore
//! t(("置顶", "Pin", "置頂", "ピン留め", "Закрепить"))
//! ```
//!
//! 158 个调用点全都得改，且以后每动一条文案就要同时维护五份——漏一份
//! 编译期毫无提示，运行期静默显示错语言。这不叫国际化，叫埋雷。
//!
//! 因此：**中文/英文仍是唯一的内联源**，另外三种语言放本目录，
//! 以中文为键查找，找不到就回落到英文。
//!
//! # 为什么用中文当键是安全的
//!
//! 原设计反对「键名目录」的三条理由，这里都不触发：
//!
//! 1. **不需要起名**——键就是已经写在调用点上的中文，没有第二套命名；
//! 2. **漂移仍可见**——中英漂移依旧在调用点相邻处暴露，本目录只负责
//!    「已定稿的中文 → 其它语言」的映射，不参与语义决策；
//! 3. **无热加载需求**——与原先一致，间接层没有额外代价。
//!
//! # 增量覆盖
//!
//! 表允许**部分覆盖**：缺的条目自动回落英文（见 [`super::Locale::pick`]）。
//! 所以新增一种语言不必等 142 条全译完才能合入，也不会因为漏译而显示
//! 中文以外的第三种语言（那比显示英文更糟）。
//!
//! # 占位符纪律
//!
//! 译文里的 `{a}` / `{b}` / `{e}` / `{name}` / `{n}` 必须与中文**逐字
//! 相同**——它们是运行时格式化参数，漏一个就是运行期 panic 或错位。
//! `i18n.rs` 的测试会逐条比对，见 `catalog_placeholders_match_source`。

